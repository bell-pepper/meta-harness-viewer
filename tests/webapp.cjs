// Run against a static server; see README for setup.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.HARNESS_TEST_URL || 'http://127.0.0.1:8090/meta-harness-viewer/';
(async () => {
 const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || (process.platform === 'linux' ? '/usr/bin/chromium' : undefined), headless:true, args:['--no-sandbox']});
 try {
  const page = await browser.newPage({viewport:{width:600,height:600}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base);
  assert.equal(await page.locator('meta[name="mrbd-web-app-capable"]').getAttribute('content'), 'yes');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('tbody tr').count(), 4);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator(':focus').getAttribute('id'), 'home-pinouts');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('input').count(), 0, 'glasses library requires no typing');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#page-image')?.naturalWidth > 0 && document.querySelector('#page-status')?.hidden);
  assert.equal(await page.locator('#position').innerText(), 'PAGE 1 / 2');
  assert(await page.locator('#prev-page').isDisabled());
  const fitSize = await page.locator('#page-image').boundingBox();
  await page.locator('#zoom').click();
  assert((await page.locator('#page-image').boundingBox()).height > fitSize.height * 1.9);
  await page.locator('#zoom').click();
  await page.screenshot({path:'/tmp/harness-reader-zoom.png'});
  await page.locator('#move').click();
  assert(await page.locator('#paper').evaluate(el => el.classList.contains('panning')));
  const before = await page.locator('#page-image').boundingBox();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('ArrowRight');
  const after = await page.locator('#page-image').boundingBox();
  assert(after.y < before.y && after.x < before.x, 'pan moves the image on both axes');
  for (let i=0;i<30;i++) await page.keyboard.press('ArrowDown');
  const edge = await page.locator('#page-image').boundingBox();
  await page.keyboard.press('ArrowDown');
  assert.equal((await page.locator('#page-image').boundingBox()).y, edge.y, 'pan clamps at the page edge');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#position').innerText(), 'PAGE 1 / 2');
  assert(!await page.locator('#paper').evaluate(el => el.classList.contains('panning')));
  await page.locator('#fit').click();
  assert(await page.locator('#move').isDisabled());
  await page.locator('#next-page').click();
  await page.waitForFunction(() => document.querySelector('#page-image')?.naturalWidth > 0 && document.querySelector('#page-status')?.hidden);
  assert.equal(await page.locator('#position').innerText(), 'PAGE 2 / 2');
  assert(await page.locator('#next-page').isDisabled());
  const overflow = await page.evaluate(() => ({body:document.documentElement.scrollHeight, main:document.querySelector('#screen').scrollHeight, visible:document.querySelector('#screen').clientHeight}));
  assert(overflow.body <= 600 && overflow.main <= overflow.visible, JSON.stringify(overflow));
  await page.screenshot({path:'/tmp/harness-reader-600.png'});
  await page.keyboard.press('Backspace');
  assert.equal(await page.locator(':focus').getAttribute('id'), 'demo-document');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator(':focus').getAttribute('id'), 'home-documents');
  await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');await page.keyboard.press('Enter');
  for(let i=0;i<3;i++) {
   assert.equal(await page.locator('#position').innerText(), `${i+1} / 3`);
   assert(await page.locator('#screen').evaluate(el => el.scrollHeight <= el.clientHeight), 'assembly fits at 600×600');
   await page.locator('#next').click();
  }
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:320,height:600});
  await page.locator('#home-documents').click();await page.locator('#demo-document').click();
  await page.waitForFunction(() => document.querySelector('#page-status')?.hidden);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= 320));
  await page.screenshot({path:'/tmp/harness-reader-320.png'});
  const meta = await page.request.get(new URL('.well-known/meta-wearables-manifest.json', base).href);
  assert(meta.ok());
  const metadata = await meta.json();
  assert.equal(metadata.name, 'Harness HUD');
  const iconURL = new URL(metadata.appearance.icon.src, meta.url());
  assert((await page.request.get(iconURL.href)).ok());
  assert((await page.request.get(new URL('assets/demo/harness-test.pdf', base).href)).ok());
  await page.goto(new URL('install.html', base).href);
  const link = await page.locator('a.action').getAttribute('href');
  assert(link.startsWith('fb-viewapp://web_app_deep_link?'));
  assert.equal(new URL(link).searchParams.get('appUrl'), 'https://bell-pepper.github.io/meta-harness-viewer/');
  // A missing image must leave working navigation and offer a retry.
  await page.route('**/assets/demo/page-*.png', r => r.abort());
  await page.goto(base);
  await page.locator('#home-documents').click();await page.locator('#demo-document').click();
  await page.waitForFunction(() => document.querySelector('#zoom')?.textContent === 'Retry');
  assert(!(await page.locator('#zoom').isDisabled()));
  await page.locator('#documents').click();
  assert.equal(await page.locator('h1').innerText(), 'Documents');
  assert.deepEqual(errors, []);
  console.log('PASS: metadata, project paths, menu and reference navigation, PDF pages, zoom, clamped pan, focus restoration, small-screen layout, installation link, and image failure recovery.');
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
